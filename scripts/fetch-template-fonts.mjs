#!/usr/bin/env node
// One-off tool: downloads the latin subset of every font the templates use from Google Fonts into
// components/templates/fonts/ and writes components/templates/template-fonts.css (@font-face with the SAME family names the
// templates already use). Run it again only to change the font list. The templates then make no request to
// fonts.googleapis.com / fonts.gstatic.com (a visitor's IP was being sent to Google on every portfolio view).
// Fonts are licensed under the SIL Open Font License; see components/templates/fonts/README.md.
import fs from 'node:fs'
import path from 'node:path'

const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36'
const here = path.resolve(import.meta.dirname, '..', 'components', 'templates')
const dir = path.join(here, 'fonts')
fs.mkdirSync(dir, { recursive: true })

const FAMILIES = [
  ['Space Grotesk', 'wght@300..700'],
  ['Fraunces', 'ital,opsz,wght@0,9..144,300..600;1,9..144,300..600'],
  ['JetBrains Mono', 'wght@400..700'],
  ['Share Tech Mono', ''],
  ['Inter', 'wght@300..800'],
  ['IBM Plex Mono', 'wght@400;500;600;700'],
  ['IBM Plex Sans', 'wght@300;400;500;600'],
  ['Syne', 'wght@400..800'],
  ['DM Sans', 'ital,wght@0,300..500;1,300..500'],
  ['Playfair Display', 'wght@600..700'],
  ['Nunito', 'wght@400..900'],
  ['Plus Jakarta Sans', 'wght@400..800'],
]

let css = '/* generated by scripts/fetch-template-fonts.mjs: latin subsets, self-hosted (SIL OFL). Do not edit by hand. */\n'
const seenFiles = new Map()
for (const [name, spec] of FAMILIES) {
  const url = `https://fonts.googleapis.com/css2?family=${name.replace(/ /g, '+')}${spec ? ':' + spec : ''}&display=swap`
  const text = await (await fetch(url, { headers: { 'User-Agent': UA } })).text()
  let n = 0
  for (const block of text.split('/* ').slice(1)) {
    const label = block.slice(0, block.indexOf(' */')).trim()
    if (label !== 'latin') continue
    const body = block.slice(block.indexOf(' */') + 3)
    const src = /url\((https:[^)]+\.woff2)\)/.exec(body)?.[1]
    if (!src) continue
    let file = seenFiles.get(src)
    if (!file) {
      file = `${name.toLowerCase().replace(/ /g, '-')}-${++n}.woff2`
      fs.writeFileSync(path.join(dir, file), Buffer.from(await (await fetch(src)).arrayBuffer()))
      seenFiles.set(src, file)
    }
    css += body
      .replace(/\/\*[\s\S]*?\*\//g, '')
      .replace(/src:\s*url\([^)]+\)[^;]*;/, `src: url('./fonts/${file}') format('woff2');`)
      .replace(/\s*unicode-range:[^;]+;/, '')
      .trim() + '\n'
  }
  if (!n) throw new Error(`no latin subset found for ${name}`)
}
fs.writeFileSync(path.join(here, 'template-fonts.css'), css)
fs.writeFileSync(path.join(dir, 'README.md'), `Self-hosted web fonts for the portfolio templates (latin subset).\nAll families are licensed under the SIL Open Font License 1.1: ${FAMILIES.map((f) => f[0]).join(', ')}.\nSource: Google Fonts. Regenerate with scripts/fetch-template-fonts.mjs.\n`)
let total = 0
for (const f of fs.readdirSync(dir)) if (f.endsWith('.woff2')) total += fs.statSync(path.join(dir, f)).size
console.log(`${seenFiles.size} font files, ${(total / 1024).toFixed(0)} KB total`)
